_anchor = [None]


def _add(el):
    _anchor[0]._p.addprevious(el)


def _after(p, el):
    p._p.addnext(el)


def H(t, level=1):
    p = doc.add_heading(t, level=level)
    _add(p._p)
    return p


def P(t="", bold_lead=None):
    p = doc.add_paragraph()
    if bold_lead:
        r = p.add_run(bold_lead)
        r.bold = True
    if t:
        p.add_run(t)
    _add(p._p)
    return p


def B(t="", bold_lead=None):
    p = doc.add_paragraph(style="List Bullet")
    if bold_lead:
        r = p.add_run(bold_lead)
        r.bold = True
    if t:
        p.add_run(t)
    _add(p._p)
    return p


def FIG(path, cap, width=6.0):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(path), width=Inches(width))
    _add(p._p)
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(cap)
    r.italic = True
    r.font.size = Pt(9)
    _add(c._p)


def TB(headers, rows, widths=None, cap=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
